"""
pci/tests/test_runner.py
========================

Reproducibility tests for the canonical Monte Carlo runner utilities in
``pci.runner``. These ensure that the PKL caches under
``simulations/results/raw/`` (which back every figure in S6 and S7) can
be regenerated bit-identically at any time.
"""
from __future__ import annotations

import shutil
from pathlib import Path

import numpy as np
import pytest


