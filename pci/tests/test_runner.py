#  bandwidth_helpers (C5.1)
# ════════════════════════════════════════════════════════════════════════════

def test_silverman_h_deterministic():
    """Silverman bandwidth is a pure function of the input array."""
    from pci.runner.bandwidth_helpers import _silverman_h
    rng = np.random.default_rng(7)
    A = rng.standard_normal(500)
    h1 = _silverman_h(A)
    h2 = _silverman_h(A)
    assert h1 == h2
    assert h1 > 0


def test_median_bandwidth_deterministic():
    from pci.runner.bandwidth_helpers import _median_bandwidth
    rng = np.random.default_rng(7)
    X = rng.standard_normal((300, 2))
    b1 = _median_bandwidth(X)
    b2 = _median_bandwidth(X)
    assert b1 == b2
    assert b1 > 0


def test_compute_J_policy_true_dgp2_shape():
    """_compute_J_policy_true returns a value per dose, finite, monotone-ish."""
    from pci.runner.bandwidth_helpers import _compute_J_policy_true, _silverman_h
    from pci.dgps.michaelis_menten import MichaelisMentenDGP
    dgp = MichaelisMentenDGP(snr_W=0.95, snr_Z=0.95)
    s = dgp.generate(n=2000, seed=1)
    h_KDE = _silverman_h(s.A)
    a_grid = np.array([1.8, 2.2, 2.6, 3.0])
    J_pt = _compute_J_policy_true(dgp, a_grid, h_KDE)
    assert J_pt.shape == (4,)
    assert np.all(np.isfinite(J_pt))


def test_bandwidth_helpers_shim_identity():
    """Original dgp2_bias_diagnostics.py re-exports must be the same Python objects."""
    from pci.runner.bandwidth_helpers import _silverman_h as A
    from simulations.experiments.dgp2_bias_diagnostics import _silverman_h as B
