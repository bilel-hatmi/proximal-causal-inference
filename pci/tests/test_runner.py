def test_decompose_callable():
    """_decompose is importable and callable; signature accepts ref_idx kwarg."""
    from pci.runner.diagnostics import _decompose
    import inspect
    assert callable(_decompose)
    sig = inspect.signature(_decompose)
    assert "ref_idx" in sig.parameters, (
        "_decompose must take ref_idx (different DGPs use different default)"
    )


def test_diagnostics_shim_is_wrapper():
    """The shim wraps the canonical _decompose to preserve the local REF_IDX
    semantics. Both must be callable; identity is NOT preserved here."""
    from pci.runner.diagnostics import _decompose as canonical
    from simulations.experiments.dgp2_bias_diagnostics import _decompose as wrapped
    assert callable(canonical)
    assert callable(wrapped)
