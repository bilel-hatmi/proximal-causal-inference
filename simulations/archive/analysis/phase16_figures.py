def _load_data() -> dict:
    if not _DATA_PATH.exists():
        raise RuntimeError(
            f"phase16_synthesis_data.json not found at {_DATA_PATH}. "
            f"Run `python -m simulations.archive.utilities._phase16_synthesis` first."
        )
    return json.loads(_DATA_PATH.read_text(encoding="utf-8"))


def _parse_cell_key(key: str):
    """Parse 'n__snr' or 'snrW__snrZ' back to tuple."""
    parts = key.split("__")
    return (float(parts[0]), float(parts[1]))


