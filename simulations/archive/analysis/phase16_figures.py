# F5 -- Proxy feasibility 4-panel heatmap (from EXP-B)
# ══════════════════════════════════════════════════════════════════════════════

def fig5_proxy_feasibility(data: dict):
    cfg = data["config"]
    methods = cfg["METHODS_MAIN"]
    snr_levels = cfg["SNR_LEVELS_FEAS"]
    expb = data["expb"]

    n_methods = len(methods)
    rows = 2 if n_methods >= 3 else 1
    cols = (n_methods + rows - 1) // rows
    fig, axes = plt.subplots(rows, cols, figsize=(5 * cols, 4.5 * rows))
    if rows == 1 and cols == 1:
        axes = np.array([[axes]])
    elif rows == 1:
        axes = axes.reshape(1, -1)
    elif cols == 1:
        axes = axes.reshape(-1, 1)

    # Compute global vmin/vmax for shared colorbar
    all_bse = []
    for cell_key, cell in expb.items():
        for method in methods:
            d = cell.get(method)
            if d:
                v = d["bse_grid"][REF_IDX]
                if np.isfinite(v):
                    all_bse.append(v)
    if all_bse:
        vmin = max(np.percentile(all_bse, 5), 1e-3)
        vmax = np.percentile(all_bse, 95)
    else:
        vmin, vmax = 1e-3, 1.0

    from matplotlib.colors import LogNorm
    norm = LogNorm(vmin=vmin, vmax=vmax)

    for k, method in enumerate(methods):
        i, j = divmod(k, cols)
        ax = axes[i, j]
        bse_mat = np.full((len(snr_levels), len(snr_levels)), np.nan)
        for r, snr_W in enumerate(snr_levels):
            for c, snr_Z in enumerate(snr_levels):
                cell_key = f"{snr_W}__{snr_Z}"
                d = expb.get(cell_key, {}).get(method)
                if d:
                    bse_mat[r, c] = d["bse_grid"][REF_IDX]

        im = ax.imshow(bse_mat, aspect="auto", cmap="RdYlGn_r", norm=norm, origin="lower")
        ax.set_xticks(range(len(snr_levels)))
        ax.set_xticklabels([str(s) for s in snr_levels])
        ax.set_yticks(range(len(snr_levels)))
        ax.set_yticklabels([str(s) for s in snr_levels])
        ax.set_title(method, fontsize=11, fontweight="bold")
        ax.set_xlabel("SNR_Z")
        ax.set_ylabel("SNR_W")
        for r in range(len(snr_levels)):
            for c in range(len(snr_levels)):
                v = bse_mat[r, c]
                if np.isfinite(v):
                    txt = f"{v:.2g}" if v < 0.01 else f"{v:.3f}"
                    ax.text(c, r, txt, ha="center", va="center",
                            color="white" if v > 1.0 else "black", fontsize=8)
        plt.colorbar(im, ax=ax, fraction=0.046, pad=0.04, label="bse_ref (log scale)")

    # Hide unused axes
    for k in range(len(methods), rows * cols):
        i, j = divmod(k, cols)
        axes[i, j].axis("off")

    fig.suptitle("F5 -- Proxy feasibility: bse_ref by (SNR_W, SNR_Z) per method",
                  fontsize=12, fontweight="bold")
    fig.tight_layout()

    out = _FIGS_DIR / "phase16_F5_proxy_feasibility.png"
    fig.savefig(out, dpi=200, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved: {out}")


