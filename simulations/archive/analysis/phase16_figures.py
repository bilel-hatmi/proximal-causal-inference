        ("J_GACE(a) = m(a)\nintegrated over policy", "Cui-style mean,\ndelta-policy = m(a)", 5.5),
        ("J(pi_{a,h})\n= integrated over\nGaussian policy", "What we ESTIMATE\n(continuous policy)", 9.5),
