# F4 -- bse vs dose curves (from EXP-A)
# ══════════════════════════════════════════════════════════════════════════════

def fig4_bse_vs_dose(data: dict):
    cfg = data["config"]
    methods = cfg["METHODS_MAIN"]
    n_list = cfg["N_LIST"]
    snr_list = cfg["SNR_LIST"]
    a_grid = np.array(cfg["A_GRID"])
    expa = data["expa"]

    fig, axes = plt.subplots(len(n_list), len(snr_list), figsize=(4 * len(snr_list), 3.5 * len(n_list)),
                              sharex=True, sharey="row")
    if len(n_list) == 1:
        axes = axes[None, :]
    if len(snr_list) == 1:
        axes = axes[:, None]

    for i, n in enumerate(n_list):
        for j, snr in enumerate(snr_list):
            ax = axes[i, j]
            cell_key = f"{n}__{snr}"
            cell = expa.get(cell_key, {})
            for method in methods:
                d = cell.get(method)
                if d is None:
                    continue
                bse = np.array(d["bse_grid"])
                ax.plot(a_grid, bse, marker="o",
                        label=METHOD_LABELS[method],
                        color=METHOD_COLORS.get(method, "grey"),
                        linewidth=2, markersize=6)
            ax.set_yscale("log")
            ax.axhline(0.1, color="grey", linestyle="--", alpha=0.5, linewidth=0.8)
            ax.set_title(f"n={n}, SNR={snr}", fontsize=10)
            if i == len(n_list) - 1:
                ax.set_xlabel("Dose a")
            if j == 0:
                ax.set_ylabel("|bias|/SE  (log scale)")
            ax.grid(True, alpha=0.3)

    # Single legend
    handles, labels = axes[0, 0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", ncol=len(methods),
                bbox_to_anchor=(0.5, 1.02), fontsize=10)

    fig.suptitle("F4 -- bse vs dose: REG > DR at boundary, DR best at centre",
                  fontsize=12, fontweight="bold", y=1.05)
    fig.tight_layout()

    out = _FIGS_DIR / "phase16_F4_bse_vs_dose.png"
    fig.savefig(out, dpi=200, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved: {out}")


