# F6 -- Spectral kappa vs bse scatter (from EXP-C)
# ══════════════════════════════════════════════════════════════════════════════

def fig6_spectral_correlation(data: dict):
    cfg = data["config"]
    methods = cfg["METHODS_MAIN"]
    expc = data["expc"]
    corrs = data["spectral_correlations"]

    fig, axes = plt.subplots(1, 2, figsize=(13, 5.5))

    for ax_idx, (diag_key, x_label) in enumerate([
        ("kappa_h_mean", "log10(kappa_h)"),
        ("kappa_r_mean", "log10(kappa_r)"),
    ]):
        ax = axes[ax_idx]
        for method in methods:
            xs, ys = [], []
            for cell_key, cell in expc.items():
                d = cell.get(method)
                if d is None:
                    continue
                x = d.get(diag_key, float("nan"))
                y = d["bse_grid"][REF_IDX]
                if np.isfinite(x) and np.isfinite(y) and x > 0:
                    xs.append(np.log10(x))
                    ys.append(y)
            if xs:
                rho_val = corrs.get(method, {}).get(diag_key, {}).get("rho", float("nan"))
                lab = f"{method} (rho={rho_val:.2f})" if np.isfinite(rho_val) else method
                ax.scatter(xs, ys, label=lab, color=METHOD_COLORS.get(method, "grey"),
                            s=80, alpha=0.85, edgecolors="black", linewidth=0.5)
        ax.set_xlabel(x_label, fontsize=11)
        ax.set_ylabel("bse_ref (observed)", fontsize=11)
        ax.set_yscale("log")
        ax.set_title(f"Spectral health: {diag_key.replace('_mean', '')}", fontsize=11, fontweight="bold")
        ax.grid(True, alpha=0.3)
        ax.legend(fontsize=9, loc="best")

    fig.suptitle("F6 -- Spectral diagnostics vs observed bse_ref (per method, across cells)",
                  fontsize=12, fontweight="bold")
    fig.tight_layout()

    out = _FIGS_DIR / "phase16_F6_spectral_correlation.png"
    fig.savefig(out, dpi=200, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved: {out}")


