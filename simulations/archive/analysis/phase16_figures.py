# F2 -- DGP1 sanity heatmap (from existing E1 pkls)
# ══════════════════════════════════════════════════════════════════════════════

def fig2_dgp1_sanity():
    methods_order = ["oracle", "linearREG", "linearDR", "KPVREG", "DRKPV",
                     "best_bennett", "best_kallus", "naiveREG"]
    n_list = [1000, 2000]
    metric_data = np.full((len(methods_order), len(n_list)), np.nan)
    cov_data = np.full((len(methods_order), len(n_list)), np.nan)

    for j, n in enumerate(n_list):
        cell_dir = _E1_DIR / f"n{n}"
        if not cell_dir.exists():
            continue
        for i, method in enumerate(methods_order):
            pkl = cell_dir / f"{method}_M100.pkl"
            if not pkl.exists():
                continue
            with open(pkl, "rb") as fh:
                data = pickle.load(fh)
            recs = [r for r in data["records"] if r.get("error") is None]
            if not recs:
                continue
            J_pt = np.array(data["meta"]["J_policy_true"])
            J_dr = np.array([r["J_dr"] for r in recs])
            V_hg = np.array([r["V_hat_grid"] for r in recs])
            with np.errstate(invalid="ignore"):
                se = np.sqrt(np.maximum(V_hg, 0.0) / n)
            ref = min(REF_IDX, J_pt.shape[0] - 1)
            bias = float(np.mean(J_dr[:, ref]) - J_pt[ref])
            se_m = float(np.nanmean(se[:, ref]))
            metric_data[i, j] = abs(bias) / se_m if se_m > 1e-15 else float("nan")
            cov_data[i, j] = float(np.mean(np.abs(J_dr[:, ref] - J_pt[ref]) <= 1.96 * se[:, ref]))

    fig, axes = plt.subplots(1, 2, figsize=(11, 5))

    for ax, data, title, vmin, vmax, cmap in [
        (axes[0], metric_data, "bse_ref (|bias|/SE)", 0, 2, "Reds"),
        (axes[1], cov_data, "Coverage (target=0.95)", 0.5, 1.0, "RdYlGn"),
    ]:
        im = ax.imshow(data, aspect="auto", cmap=cmap, vmin=vmin, vmax=vmax)
        ax.set_xticks(range(len(n_list)))
        ax.set_xticklabels([f"n={n}" for n in n_list])
        ax.set_yticks(range(len(methods_order)))
        ax.set_yticklabels(methods_order)
        ax.set_title(f"DGP1 {title}", fontsize=11, fontweight="bold")
        for i in range(len(methods_order)):
            for j in range(len(n_list)):
                v = data[i, j]
                if np.isfinite(v):
                    ax.text(j, i, f"{v:.3f}", ha="center", va="center",
                            color="white" if (cmap == "Reds" and v > 1) or (cmap == "RdYlGn" and v < 0.7) else "black",
                            fontsize=9)
        plt.colorbar(im, ax=ax, fraction=0.046, pad=0.04)

    fig.tight_layout()

    out = _FIGS_DIR / "phase16_F2_dgp1_sanity.png"
    fig.savefig(out, dpi=200, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved: {out}")


# ══════════════════════════════════════════════════════════════════════════════
# F3 -- DGP2 coverage heatmap (from EXP-A)
# ══════════════════════════════════════════════════════════════════════════════

def fig3_coverage_map(data: dict):
    cfg = data["config"]
    methods = cfg["METHODS_MAIN"]
    n_list = cfg["N_LIST"]
    snr_list = cfg["SNR_LIST"]
    expa = data["expa"]

    fig, axes = plt.subplots(1, len(methods), figsize=(4 * len(methods), 4.5), sharey=True)
    if len(methods) == 1:
        axes = [axes]

    for k, method in enumerate(methods):
        ax = axes[k]
        cov = np.full((len(snr_list), len(n_list)), np.nan)
        for i, snr in enumerate(snr_list):
            for j, n in enumerate(n_list):
                cell_key = f"{n}__{snr}"
                d = expa.get(cell_key, {}).get(method)
                if d:
                    cov[i, j] = d["cov_grid"][REF_IDX]

        im = ax.imshow(cov, aspect="auto", cmap="RdYlGn", vmin=0.5, vmax=1.0, origin="lower")
        ax.set_xticks(range(len(n_list)))
        ax.set_xticklabels([f"n={n}" for n in n_list])
        ax.set_yticks(range(len(snr_list)))
        ax.set_yticklabels([f"SNR={s}" for s in snr_list])
        ax.set_title(method, fontsize=11, fontweight="bold")
        for i in range(len(snr_list)):
            for j in range(len(n_list)):
                v = cov[i, j]
                if np.isfinite(v):
                    color = "white" if v < 0.7 else "black"
                    ax.text(j, i, f"{v:.3f}", ha="center", va="center",
                            color=color, fontsize=10, fontweight="bold")
        if k == len(methods) - 1:
            plt.colorbar(im, ax=ax, fraction=0.046, pad=0.04, label="Coverage (target=0.95)")

    fig.suptitle("F3 -- DGP2 coverage map: where does each method achieve nominal coverage?",
                  fontsize=12, fontweight="bold")
    fig.tight_layout()

    out = _FIGS_DIR / "phase16_F3_coverage_map.png"
    fig.savefig(out, dpi=200, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved: {out}")


